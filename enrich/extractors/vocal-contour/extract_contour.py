#!/usr/bin/env python3
"""Bounded model adapter for the vocal contour recipe; never writes an archive.

External model trees and weights are operator provisioned, checked before import,
and never downloaded. Each 20s target gets its own forward 30s pitch context
and a separate RWBD context beginning 5s before the target (clamped at zero).
Tail model contexts are zero padded to30s; only actual target samples produce
rows or note events (the last partial10ms target row is zero padded). Regions have their own declared window origin, not whole-run
context equivalence. Audio is decoded again because frames lacks waveform.
"""
from __future__ import annotations
import hashlib
import json
import math
import os
from pathlib import Path
import platform
import subprocess
import sys
from typing import Any


ENRICH = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ENRICH))
import vocal_contour as core  # noqa: E402

PESTO_SHA = '16c32e06ddd950e3e4866dfa3c7f8a87c4988f8adf43e57977b189f031f26f3e'
RMVPE_SHA = '6d62215f4306e3ca278246188607209f09af3dc77ed4232efdd069798c4ec193'
RWBD_SHA = '0bc2d42a6d4b7a05436deb937e2deda1c12de49e5687cfda0bdf6a430120dcd2'
RUNTIME = {'pesto-pitch': '2.0.1', 'torch': '2.14.1+cpu', 'numpy': '2.5.4',
           'scipy': '1.18.1', 'librosa': '1.0.0', 'PyYAML': '6.0.3'}
PYTHON = '3.12.15'


def _load_numpy() -> None:
    """Numerical dependencies are lazy: importing the adapter is inert."""
    global np
    import numpy as np


def parameters() -> dict[str, Any]:
    return dict(recipe='gesture-rmvpe-moving-rwbd-1', step_ms=10, target_seconds=20,
                pitch_context_seconds=30, boundary_context_seconds=30, boundary_preroll_seconds=5,
                head_context='clamp', tail_context='zero-pad-to-context', region_windows='relative-to-input',
                rmvpe_source='', rosvot_source='', rmvpe_code_sha256='', rosvot_code_sha256='',
                rmvpe_weights='', rwbd_weights='', rmvpe_weights_sha256=RMVPE_SHA,
                rwbd_weights_sha256=RWBD_SHA, pesto_weights_sha256=PESTO_SHA)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def code_digest(root: Path) -> str:
    """Stable model-code pin: sorted relative .py/.yaml paths, NUL, file SHA, LF.
    Checkpoints are separately pinned; caches and generated bytecode are excluded.
    """
    h = hashlib.sha256()
    for p in sorted(root.rglob('*')):
        if p.is_file() and p.suffix in ('.py', '.yaml'):
            h.update(p.relative_to(root).as_posix().encode() + b'\0' + digest(p).encode() + b'\n')
    return h.hexdigest()


def settings(given: dict[str, Any]) -> dict[str, Any]:
    defaults = parameters()
    paths = {'rmvpe_source', 'rosvot_source', 'rmvpe_code_sha256', 'rosvot_code_sha256', 'rmvpe_weights', 'rwbd_weights'}
    if set(given) != set(defaults) or any(given[k] != defaults[k] for k in defaults.keys() - paths):
        raise ValueError('vocal-contour has a fixed recipe; unsupported parameters')
    for k in paths:
        if not isinstance(given[k], str) or not given[k]:
            raise ValueError(f'configure vocal-contour parameter {k}; no model downloads or fallback')
    for kind in ('rmvpe', 'rosvot'):
        root = Path(given[f'{kind}_source'])
        if not root.is_dir() or code_digest(root) != given[f'{kind}_code_sha256']:
            raise ValueError(f'{kind} source is missing or its code digest differs')
    for kind in ('rmvpe', 'rwbd'):
        p = Path(given[f'{kind}_weights'])
        if not p.is_file() or digest(p) != given[f'{kind}_weights_sha256']:
            raise ValueError(f'{kind} weights missing or digest differs')
    return given


def decode(path: str, start: float, duration: float, rate: int) -> np.ndarray:
    _load_numpy()
    args = ['ffmpeg', '-nostdin', '-hide_banner', '-nostats', '-loglevel', 'error', '-threads', '1',
            '-ss', str(start), '-t', str(duration), '-i', path, '-map', '0:a:0', '-ac', '1',
            '-ar', str(rate), '-f', 'f32le', '-']
    p = subprocess.run(args, capture_output=True, stdin=subprocess.DEVNULL)
    if p.returncode or len(p.stdout) % 4:
        raise ValueError(f'ffmpeg decode failed: {p.stderr.decode(errors="replace")[:300]}')
    return np.frombuffer(p.stdout, '<f4').copy()


class Models:
    def __init__(self, config: dict[str, Any]):
        _load_numpy()
        import importlib.metadata
        import types
        import torch
        import yaml
        import pesto
        if platform.python_version() != PYTHON:
            raise ValueError(f'vocal-contour requires python=={PYTHON}')
        for package, expected in RUNTIME.items():
            if importlib.metadata.version(package) != expected:
                raise ValueError(f'vocal-contour requires {package}=={expected}')
        from pesto.loader import load_model
        torch.set_num_threads(2)
        self.torch = torch
        if importlib.metadata.version('pesto-pitch') != '2.0.1':
            raise ValueError('vocal-contour requires pesto-pitch==2.0.1')
        checkpoint = Path(pesto.__file__).parent / 'weights/mir-1k_g7.ckpt'
        if digest(checkpoint) != PESTO_SHA:
            raise ValueError('PESTO checkpoint digest differs')
        self.pesto = load_model(str(checkpoint), 10., sampling_rate=16000)
        self.pesto.reduction = 'alwa'
        sys.path.insert(0, config['rmvpe_source'])
        sys.path.insert(0, config['rosvot_source'])
        # The official numerical utility imports unused optional MIDI I/O.
        # Drop that import only, preserving all numerical functions verbatim.
        source = Path(config['rosvot_source'])
        name = 'utils.audio.pitch_utils'
        pu = types.ModuleType(name)
        sys.modules[name] = pu
        p = source / 'utils/audio/pitch_utils.py'
        exec(compile(p.read_text().replace('import pretty_midi', ''), str(p), 'exec'), pu.__dict__)
        self.pu = pu
        import rmvpe
        from modules.rosvot.rosvot import WordbdExtractor
        from utils.audio.mel import MelNet
        self.rmvpe = rmvpe.RMVPE(config['rmvpe_weights'], False, device='cpu')
        self.hp = yaml.safe_load((source / 'checkpoints/rosvot/config.yaml').read_text())
        self.wh = yaml.safe_load((source / 'checkpoints/rwbd/config.yaml').read_text())
        self.wh['word_bd_threshold'] = .5
        self.word = WordbdExtractor(self.wh).eval()
        ck = torch.load(config['rwbd_weights'], map_location='cpu', weights_only=True)
        state = ck['state_dict']
        state = {k[6:]: v for k, v in state.items() if k.startswith('model.')} if any('.' in k for k in state) else state['model']
        self.word.load_state_dict(state, strict=True)
        self.melnet = MelNet(self.hp)
        self.software = [{'name': name, 'version': version} for name, version in RUNTIME.items()]
        self.software.append({'name': 'python', 'version': PYTHON})
        ffmpeg = subprocess.run(['ffmpeg', '-version'], check=True, capture_output=True, text=True)
        version = ffmpeg.stdout.splitlines()[0].split()
        self.software.append({'name': 'ffmpeg', 'version': version[2]})

    def pitch(self, audio: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        with self.torch.inference_mode():
            f, c, _, _ = self.pesto(self.torch.from_numpy(audio), sr=16000, convert_to_freq=True, return_activations=True)
            other = self.rmvpe.infer_from_audio(audio, thred=.03)
        return f.reshape(-1).numpy(), c.reshape(-1).numpy(), np.asarray(other)

    def boundaries(self, audio24k: np.ndarray) -> list[float]:
        import librosa
        torch, hp, wh, pu = self.torch, self.hp, self.wh, self.pu
        with torch.inference_mode():
            f0 = self.rmvpe.infer_from_audio(librosa.resample(audio24k, orig_sr=24000, target_sr=16000), thred=.03)
            mel = self.melnet(torch.tensor(audio24k).unsqueeze(0))
            real = mel.shape[1]
            rows = int(np.ceil(real / hp['frames_multiple']) * hp['frames_multiple'])
            mel = torch.nn.functional.pad(mel, (0, 0, 0, rows - real))
            f = pu.resample_align_curve(np.asarray(f0), .01, hp['hop_size'] / hp['audio_sample_rate'], align_length=rows)
            norm, uv = pu.norm_interp_f0(f)
            nf, uvt = torch.tensor(norm).unsqueeze(0), torch.tensor(uv).long().unsqueeze(0)
            coarse = pu.f0_to_coarse(pu.denorm_f0(nf, uvt))
            out = self.word(mel=mel[:, :, :wh.get('use_mel_bins', 80)], pitch=coarse, uv=uvt,
                            non_padding=mel.abs().sum(-1) > 0, train=False)
            return (torch.nonzero(out['word_bd_pred'][0, :real]).flatten().numpy() * hp['hop_size'] / hp['audio_sample_rate']).tolist()


def levels(audio: np.ndarray, rows: int) -> np.ndarray:
    _load_numpy()
    cumulative = np.r_[0., np.cumsum(audio.astype(np.float64) ** 2)]
    centres = np.arange(rows) * 160
    lo, hi = np.clip(centres - 160, 0, len(audio)), np.clip(centres + 160, 0, len(audio))
    return (10 * np.log10(np.maximum(np.maximum(cumulative[hi] - cumulative[lo], 0) / 320, 1e-12))).astype('<f4')


def aligned(x: np.ndarray, n: int) -> np.ndarray:
    _load_numpy()
    out = np.zeros(n, dtype=x.dtype)
    out[:min(n, len(x))] = x[:n]
    return out


def measure(path: str, models: Models) -> dict[str, Any]:
    """No whole-recording tensor: contexts bounded at30s, outputs at10ms."""
    _load_numpy()
    frame_parts, attacks, notes, windows = [], [], [], []
    start = 0
    while True:
        target = decode(path, start, 20, 16000)
        if not len(target):
            break
        n = math.ceil(len(target) / 160)
        decoded_audio = decode(path, start, 30, 16000)
        audio = np.pad(decoded_audio, (0, 30 * 16000 - len(decoded_audio)))
        f, c, r = models.pitch(audio)
        boundary_start = max(0, start - 5)
        decoded_boundary = decode(path, boundary_start, 30, 24000)
        boundary_audio = np.pad(decoded_boundary, (0, 30 * 24000 - len(decoded_boundary)))
        word = [t + boundary_start - start for t in models.boundaries(boundary_audio)
                if 0 <= t + boundary_start - start < len(target) / 16000]
        f, c, r = aligned(f, n), aligned(c, n), aligned(r, n)
        padded = np.pad(target, (0, n * 160 - len(target)))
        result = core.analyze(padded, f, c, levels(audio, n), r, word_boundaries=word)
        result['frames']['confidence'] = result['gesture']['confidence']
        frame_parts.append(result['frames'])
        for event in result['attacks']['proposals']:
            if event['selected']:
                attacks.append({'time': start + event['time_s'], 'label': 'automatic_same_pitch_articulation'})
        for note in result['notes']:
            notes.append({'start': start + note['start'], 'end': min(start + note['end'], start + len(target) / 16000),
                          'value': note['pitch'] + note.get('cents', 0) / 100})
        windows.append(dict(start=start, samples=len(target), pitch_context=[start, start + len(decoded_audio) / 16000],
                            boundary_context=[boundary_start, boundary_start + len(decoded_boundary) / 24000],
                            pitch_context_decoded_samples=len(decoded_audio), boundary_context_decoded_samples=len(decoded_boundary),
                            pitch_decoded_pcm_sha256=hashlib.sha256(decoded_audio.tobytes()).hexdigest(),
                            boundary_decoded_pcm_sha256=hashlib.sha256(decoded_boundary.tobytes()).hexdigest(),
                            pitch_padded_samples=len(audio), boundary_padded_samples=len(boundary_audio),
                            pitch_pcm_sha256=hashlib.sha256(audio.tobytes()).hexdigest(),
                            boundary_pcm_sha256=hashlib.sha256(boundary_audio.tobytes()).hexdigest(),
                            gesture=result.get('gesture'), note_reading=result['note_reading'], attacks=result['attacks']))
        start += 20
        if len(target) < 20 * 16000:
            break
    if not frame_parts:
        raise ValueError('input decodes to no audio')
    return dict(frames={k: np.concatenate([p[k] for p in frame_parts]) for k in frame_parts[0]},
                attacks=attacks, notes=notes, windows=windows)


def json_values(value: Any) -> Any:
    """NaN denotes missing raw tracker pitch, never a JSON pitch event."""
    _load_numpy()
    if isinstance(value, np.ndarray):
        return json_values(value.tolist())
    if isinstance(value, np.generic):
        return json_values(value.item())
    if isinstance(value, dict):
        return {key: json_values(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_values(item) for item in value]
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def write(output: Path, measured: dict[str, Any], config: dict[str, Any], software: list[dict[str, str]]) -> None:
    _load_numpy()
    f = measured['frames']
    columns = {'pitch': ('new_render_midi', '<f4'), 'voiced': ('voiced', 'u1'),
               'held': ('held', 'u1'), 'confidence': ('confidence', '<f4')}
    outputs = {}
    for name, (key, dtype) in columns.items():
        data = np.asarray(f[key], dtype=dtype).reshape(-1, 1)
        (output / f'{name}.{ "u8" if dtype == "u1" else "f32"}').write_bytes(data.tobytes())
        outputs[name] = {'shape': list(data.shape)}
    for name in ('attacks', 'notes'):
        (output / f'{name}.json').write_text(json.dumps(measured[name], allow_nan=False))
        outputs[name] = {}
    provenance = dict(recipe=config, core_settings=core.SETTINGS, note_settings=core.NOTE_SETTINGS, runtime=RUNTIME, python=PYTHON, windows=measured['windows'], region_policy='windows relative to supplied input; no whole-context equivalence',
                      limitations=['Monophonic model can follow bleed/harmony; source identity is unverified.',
                                   'Automatic boundaries are articulation proposals, not word or note truth.',
                                   'Window joins do not establish repeated form, meter or attack accuracy.',
                                   'Notes are a lossy reading: unresolved runs receive median-pitch spans flagged in note_reading.uncertain_regions; contour retains motion.'])
    (output / 'provenance.json').write_text(json.dumps(json_values(provenance), allow_nan=False))
    outputs['provenance'] = {}
    outputs['voiced_fraction'] = {'value': float(np.mean(f['voiced']))}
    result = dict(contract='archive-extractor-result/1', software=software,
                  grids={'contour': {'sample_rate': 16000, 'hop': 160, 'first_centre': 0}}, outputs=outputs)
    (output / 'result.json').write_text(json.dumps(result, allow_nan=False))


def main(argv: list[str]) -> int:
    try:
        if len(argv) != 1:
            raise ValueError('usage: extract_contour.py request.json')
        request = json.loads(Path(argv[0]).read_text())
        config = settings(request['parameters'])
        models = Models(config)
        write(Path(request['output_dir']), measure(request['input']['path'], models), config, models.software)
    except (ValueError, OSError, KeyError, ImportError, RuntimeError) as exc:
        print(f'vocal-contour: {exc}', file=sys.stderr)
        return 1
    return 0

if __name__ == '__main__':
    # The two-thread model policy belongs to this executable process only.
    # Pin before main loads NumPy; library imports preserve their caller's policy.
    for key in ('OMP_NUM_THREADS', 'MKL_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'NUMBA_NUM_THREADS'):
        os.environ[key] = '2'
    raise SystemExit(main(sys.argv[1:]))
